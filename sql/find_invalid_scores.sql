-- Identify invalid scores and their users
SELECT 
    u.id as user_id, 
    u.display_name, 
    s.title, 
    s.difficulty_name, 
    s.score as actual_score, 
    t.max_score as theoretical_max
FROM scores s
JOIN temp_song_theory t ON s.title = t.title AND s.difficulty_name = t.diff
JOIN users u ON s.user_id = u.id
WHERE s.score > t.max_score
ORDER BY u.id;

-- Summary of count per user
SELECT 
    u.id, 
    u.display_name, 
    COUNT(*) as invalid_score_count
FROM scores s
JOIN temp_song_theory t ON s.title = t.title AND s.difficulty_name = t.diff
JOIN users u ON s.user_id = u.id
WHERE s.score > t.max_score
GROUP BY u.id, u.display_name;
