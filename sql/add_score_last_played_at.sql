-- リーグの活動判定を「有効曲（ライン超え）が 0 か」から
-- 「課題曲の最終プレー日時が開催期間内にあるか」へ変更したことに伴うスキーマ変更と、
-- 旧ルールで積み上がった自動休止カウンタのリセット。
--
-- ※ このファイルは記録・確認用。デプロイすれば手で流さなくても自動で同じ状態になる。
--   (1) は application.yml の hibernate.ddl-auto=update が自動追加する。
--   (2)(3) は DataInitializer の runOnce("league-reset-inactive-weeks-for-lastplay-rule")
--   が起動時に 1 度だけ実行する（applied_migrations テーブルに実行済みを記録するため、
--   再起動で繰り返し実行されて自動休止が機能しなくなることはない）。
--   手で先に流した場合は、対象行が無くなるだけで二重適用の害は無い。

-- ---------------------------------------------------------------------------
-- (1) 最終プレー日時の保存先を追加する
-- ---------------------------------------------------------------------------
-- 公式 CSV の「最終プレー日時」列（JST 壁時計）を取り込み時に保存する。
-- uploadedAt（サーバー時計・記録が伸びたときだけ進む）とは別物で、こちらは
-- 自己ベストが更新されなくても「遊べば進む」ため、リーグの活動判定に使える。
-- 列を持たない取り込み経路（ブックマークレット CSV は空欄・INFINITAS は別書式）では
-- NULL のまま＝「不明」として扱う。
ALTER TABLE scores
ADD COLUMN IF NOT EXISTS last_played_at TIMESTAMP;

-- ---------------------------------------------------------------------------
-- (2) 旧ルールで自動休止されたエントリーを参加中に戻す
-- ---------------------------------------------------------------------------
-- 自動休止の判定は「連続 3 週 inactive」なので、inactive_weeks >= 3 かつ active=false が
-- 自動休止の痕跡になる（自主離脱 LeagueService.leave は inactive_weeks を触らないため、
-- 通常この条件には該当しない）。
-- 実行順に注意: 先に (3) でカウンタを 0 にすると、ここで対象を特定できなくなる。
UPDATE league_entries
   SET active = TRUE
 WHERE active = FALSE
   AND inactive_weeks >= 3;

-- ---------------------------------------------------------------------------
-- (3) 旧ルールで積み上がった不参加カウントを 0 に戻す
-- ---------------------------------------------------------------------------
-- 【なぜ「プレシーズンの再判定」ではなく「リセット」なのか】
-- 新しい判定が使う scores.last_played_at は (1) で初めて追加する列で、過去のアップロードでは
-- 一切保存していない。したがって「プレシーズン（2026-08-03 週）当時、誰が課題曲を遊んでいたか」
-- を後から復元する手段が無い（当時のスコア行にも履歴ログにも最終プレー日時は残っていない）。
-- 今から CSV を再取り込みしても、CSV が持つのは「現時点の最終プレー日時」であり、
-- その後の週に同じ曲を遊んでいれば当時の値は上書きされて消えている。
--
-- 締め済みの週はすべて旧ルール（有効曲 0 = 不参加）で判定されているため、
-- 積み上がったカウントは新ルールでは根拠が無い。誤って不参加を数えられた人を
-- 残す方が実害が大きいので、全エントリーのカウンタを 0 に戻して仕切り直す。
-- 以降の週は新ルール（LeagueWeekLifecycleService.playedDuringWeek）で数え直される。
UPDATE league_entries
   SET inactive_weeks = 0
 WHERE inactive_weeks > 0;

